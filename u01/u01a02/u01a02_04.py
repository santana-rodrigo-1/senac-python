# Média escolar

n1 = int (input ("Digite a nota 1: "))
n2 = int (input ("Digite a nota 2: "))
n3 = int (input ("Digite a nota 3: "))
media = (n1 + n2 + n3) / 3

print("\n" + "+" + "-" * 25 + "+" + "\n")
print(f"A média das notas {n1} + {n2} + {n3} = {media:.1f}")
print("\n" + "+" + "-" * 25 + "+" + "\n")
