# 2 — Aumento de salário
# Peça ao usuário o valor do salário e calcule quanto ele passará a receber com um aumento de 10%.
# Dica: Lembre-se: aumentar 10% é o mesmo que multiplicar o valor por 1.10.

salario = float(input("Digite valor do salário: "))

aumento = salario * 0.10

print(f"Salário atual: {salario}")
print(f"Salário com aumento de 10%: {aumento}")
