# Temperatura

celsius = float (input(f"Digite a temperatura em Celsius: "))
fahrenheit = (celsius * 9 / 5) # formula °F = (°C × 9 ÷ 5)

print("\n" + "+" + "-" * 25 + "+" + "\n")
print(f"A temperatura digitada em Celsius: {celsius}")
print(f"Convertendo para Fahrenheit: {fahrenheit}")
print("\n" + "+" + "-" * 25 + "+" + "\n")
